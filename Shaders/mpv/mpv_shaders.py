"""Translates mpv / libplacebo user shaders into Direct3D 11 HLSL passes.

Each pass of a user shader becomes a complete GLSL 450 shader: the pass body,
with the macros libplacebo defines around it (NAME_tex, NAME_texOff, NAME_pos,
NAME_gather, ...). glslang compiles it to SPIR-V and SPIRV-Cross turns that into
HLSL shader model 5 -- the route libplacebo itself takes on Direct3D 11 -- so
matrix order, gathers and integer arithmetic keep their GLSL meaning exactly.

Compute passes written for workgroup-shared memory (ArtCNN keeps its 3x3
neighbourhood in a `shared` array filled once per workgroup) keep it where it pays,
with its size given in numbers, and fetch the neighbourhood per invocation where it
does not: the same texels, the same weights (unshare).

Two uses:

    python mpv_shaders.py <shader> <output dir> [--tools <dir>]

        One shader into HLSL passes and a manifest listing what each pass binds
        and how big its output is, for the DLSS 5 harness
        (tools/dlssnr_probe/mpvhook.inl), which compiles them when it runs.

    python mpv_shaders.py renderer [--upstream <dir>] [--tools <dir>]

        The prescalers the renderer embeds (FSRCNNX 8 and 16, RAVU-zoom and
        ArtCNN C4F16 DS): their
        passes under Shaders/mpv/<shader>/, lookup tables as half floats next to
        them, the tables in Source/Upscale/MpvShaderTables.h, and the generated
        blocks of Shaders/compile_shaders.cmd and Source/res/MpcVideoRenderer.rc2.
        Build the Shaders project again afterwards (compile_shaders.cmd), since the
        passes are not items of it.

--upstream is where the user shaders are (tools/dlssnr_probe/upscalers by
default), --tools where glslang and spirv-cross are (its tools folder).
"""

import os
import re
import subprocess
import sys

MAX_BINDS = 8
MAX_PARAMS = 8

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))

# The prescalers in the renderer: file, C++ name, name the renderer shows.
RENDERER_SHADERS = [
    ("FSRCNNX_x2_8-0-4-1.glsl", "FSRCNNX8", "FSRCNNX 8"),
    ("FSRCNNX_x2_16-0-4-1.glsl", "FSRCNNX16", "FSRCNNX 16"),
    ("ravu-zoom-ar-r3.hook", "RavuZoomAR3", "RAVU-zoom"),
    ("ArtCNN_C4F16_DS.glsl", "ArtCNNC4F16DS", "ArtCNN C4F16 DS"),
]
FIRST_RESOURCE_ID = 2000

CMD_BEGIN = "REM mpv prescalers: generated by mpv\\mpv_shaders.py, do not edit this block"
CMD_END = "REM end of the mpv prescalers"
RC_BEGIN = "// mpv prescalers: generated by Shaders/mpv/mpv_shaders.py, do not edit this block"
